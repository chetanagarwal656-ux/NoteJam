import { RawMindmapData, ExtractedContent, MindmapSectionInput } from "./types";

export const extractContent = (raw: RawMindmapData): ExtractedContent => {
  const m = raw || {};
  const title = (m.title || m.centralTopic || "Study Map").trim();
  const centralConcept = (m.centralConcept || m.centralTopic || m.title || "Central Concept").trim();
  
  let centralList = m.centralList || [];
  if (centralList.length === 0 && m.thesis) {
    centralList = [m.thesis];
  }
  if (centralList.length === 0 && m.centerSummary && m.centerSummary.length > 0) {
    centralList = m.centerSummary;
  }

  let sections: MindmapSectionInput[] = m.sections || [];

  // Compatibility for mind maps generated by the short-lived sticky-note format.
  // This ensures saved notes continue to open after the renderer upgrade.
  if (sections.length === 0 && m.stickyNotes && m.stickyNotes.length > 0) {
    sections = m.stickyNotes.map((note, idx) => ({
      title: note.title || `Topic ${idx + 1}`,
      cue: ["WHAT IS IT?", "WHY IT MATTERS", "HOW IT WORKS"][idx % 3],
      bullets: String(note.content || "").split(/(?<=[.!?])\s+/).filter(Boolean).slice(0, 3),
    }));
  }

  // Fallback for older formats (branches or nodes)
  if (sections.length === 0 && m.branches && m.branches.length > 0) {
    sections = m.branches.map((branch, idx) => ({
      title: branch.title || `Topic ${idx + 1}`,
      cue: branch.prompt || ["WHAT IS IT?", "WHY USE IT?", "HOW USED?"][idx % 3],
      bullets: branch.bullets || [],
      icon: branch.icon,
    }));
  }

  if (sections.length === 0 && m.nodes && m.nodes.length > 0) {
    sections = m.nodes.slice(0, 6).map((node, idx) => ({
      title: node.id || `Topic ${idx + 1}`,
      cue: ["WHAT IS IT?", "WHY USE IT?", "KEY POINT"][idx % 3],
      bullets: [node.label || node.id || ""].filter(Boolean),
    }));
  }

  const validSections = sections.filter((s) => s && (s.title || (s.bullets && s.bullets.length > 0)));

  return {
    title,
    centralConcept,
    centralList: centralList.slice(0, 3),
    sections: validSections,
  };
};
